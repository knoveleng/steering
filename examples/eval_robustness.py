#!/usr/bin/env python3
"""
Step 2: Evaluate robustness benchmark responses.

This script evaluates model responses generated by generate_robustness.py
using an LLM judge to compare with ground truth answers.

Usage:
    python examples/eval_robustness.py \
        --input-dir logs/robustness/basic/Qwen2.5-3B-Instruct \
        --output-dir logs/robustness/basic/Qwen2.5-3B-Instruct \
        --benchmark tinyMMLU
"""

import argparse
import json
import os
from pathlib import Path
from typing import Dict, Any, List, Optional

from steering.evaluation.robustness import BenchmarkRegistry, RobustnessEvaluator
from steering.utils.logger import setup_logger

logger = setup_logger("steering.example.eval_robustness")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Evaluate robustness benchmark responses",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter
    )
    
    parser.add_argument(
        "--input-dir",
        type=str,
        required=True,
        help="Directory containing JSON files with responses from generate_robustness.py"
    )
    
    parser.add_argument(
        "--output-dir",
        type=str,
        required=True,
        help="Output directory for evaluation results"
    )
    
    parser.add_argument(
        "--benchmark",
        type=str,
        required=True,
        choices=BenchmarkRegistry.list_benchmarks(),
        help="Benchmark name (must match the one used in generation)"
    )
    
    parser.add_argument(
        "--file-pattern",
        type=str,
        default="*.json",
        help="Glob pattern to match input files"
    )
    
    parser.add_argument(
        "--max-samples",
        type=int,
        default=None,
        help="Maximum number of samples to evaluate per file"
    )
    
    # Judge model options
    parser.add_argument(
        "--judge-model",
        type=str,
        default="Qwen/Qwen2.5-14B-Instruct",
        help="Model to use as LLM judge"
    )
    
    parser.add_argument(
        "--tensor-parallel-size",
        type=int,
        default=1,
        help="Tensor parallel size for judge model"
    )
    
    parser.add_argument(
        "--gpu-memory-utilization",
        type=float,
        default=0.9,
        help="GPU memory utilization for judge model"
    )
    
    return parser.parse_args()


def validate_args(args: argparse.Namespace) -> None:
    """Validate command line arguments."""
    if not os.path.isdir(args.input_dir):
        raise ValueError(f"Input directory does not exist: {args.input_dir}")
    
    if args.max_samples is not None and args.max_samples <= 0:
        raise ValueError(f"max-samples must be positive, got: {args.max_samples}")


def load_json_file(file_path: Path) -> Dict[str, Any]:
    """Load and validate JSON file."""
    try:
        with open(file_path, "r") as f:
            data = json.load(f)
        
        # Validate required fields
        if "results" not in data:
            raise ValueError(f"Missing 'results' field in {file_path}")
        
        if "metadata" not in data:
            logger.warning(f"Missing 'metadata' field in {file_path}, using empty dict")
            data["metadata"] = {}
        
        return data
    except json.JSONDecodeError as e:
        raise ValueError(f"Invalid JSON in {file_path}: {e}")
    except Exception as e:
        raise ValueError(f"Error reading {file_path}: {e}")


def evaluate_file(
    file_path: Path,
    evaluator: RobustnessEvaluator,
    output_dir: Path,
    benchmark_name: str,
    max_samples: Optional[int] = None,
) -> None:
    """Evaluate a single file.
    
    Args:
        file_path: Path to input JSON file
        evaluator: RobustnessEvaluator instance
        output_dir: Output directory for results
        benchmark_name: Name of the benchmark
        max_samples: Maximum number of samples to evaluate
    """
    logger.info(f"Evaluating {file_path.name}...")
    
    # Load data
    data = load_json_file(file_path)
    degree = data.get("degree")
    metadata = data.get("metadata", {})
    results = data["results"]
    
    # Validate benchmark matches
    file_benchmark = metadata.get("benchmark")
    if file_benchmark and file_benchmark != benchmark_name:
        logger.warning(
            f"Benchmark mismatch: file has {file_benchmark}, expected {benchmark_name}"
        )
    
    # Extract prompts, responses, and ground truths
    prompts = [r["prompt"] for r in results]
    responses = [r["response"] for r in results]
    ground_truths = [r.get("ground_truth", "") for r in results]
    
    # Limit samples if specified
    if max_samples is not None:
        prompts = prompts[:max_samples]
        responses = responses[:max_samples]
        ground_truths = ground_truths[:max_samples]
        results = results[:max_samples]
    
    if not prompts or not responses:
        logger.warning(f"No valid prompts/responses found in {file_path}")
        return
    
    # Evaluate
    accuracy, labels = evaluator.evaluate(
        prompts, 
        responses, 
        ground_truths=ground_truths,
        return_labels=True
    )
    logger.info(f"Accuracy: {accuracy:.4f} ({sum(labels)}/{len(labels)}) - Degree: {degree}")
    
    # Update metadata with accuracy
    metadata["accuracy"] = accuracy
    metadata["correct"] = sum(labels)
    metadata["total"] = len(labels)
    
    # Update labels in results
    for i, label in enumerate(labels):
        results[i]["correct"] = label
    
    # Create output directory
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Generate output filename
    output_file = output_dir / f"{file_path.stem}_evaluated.json"
    
    # Save results
    with open(output_file, "w") as f:
        json.dump({
            "degree": degree,
            "metadata": metadata,
            "results": results
        }, f, indent=2, ensure_ascii=False)
    
    logger.info(f"Results saved to {output_file}")


def main() -> None:
    args = parse_args()
    validate_args(args)
    
    # Convert to Path objects
    input_dir = Path(args.input_dir)
    output_dir = Path(args.output_dir)
    
    # Find input files
    input_files = sorted(input_dir.glob(args.file_pattern))
    
    if not input_files:
        logger.warning(f"No files found matching pattern '{args.file_pattern}' in {input_dir}")
        return
    
    logger.info(f"Found {len(input_files)} file(s) to evaluate")
    logger.info(f"Benchmark: {args.benchmark}")
    logger.info(f"Judge model: {args.judge_model}")
    
    # Initialize evaluator
    evaluator = RobustnessEvaluator({
        "benchmark": args.benchmark,
        "model": args.judge_model,
        "tensor_parallel_size": args.tensor_parallel_size,
        "gpu_memory_utilization": args.gpu_memory_utilization,
    })
    
    # Evaluate each file
    for file_path in input_files:
        try:
            evaluate_file(
                file_path,
                evaluator,
                output_dir,
                args.benchmark,
                args.max_samples
            )
        except Exception as e:
            logger.error(f"Error evaluating {file_path}: {e}")
            continue
    
    logger.info("=" * 60)
    logger.info("Evaluation completed!")
    logger.info("=" * 60)


if __name__ == "__main__":
    main()
